package com.jiang.financeagent.rag;

import java.util.List;

/**
 * Schema 切块（Chunk）—— RAG 四环节里的第一环。
 *
 * ============================================================
 * 一、为什么「表结构」也能做 RAG
 * ============================================================
 *   RAG 的本质不是"向量检索"，而是四个环节：
 *
 *     | 环节            | 通用文档 RAG      | 本项目的 Schema 召回        |
 *     |-----------------|-------------------|-----------------------------|
 *     | 切块 Chunking   | 文档切成段落       | **一张表 = 一个 chunk**      |
 *     | 索引 Indexing   | 建倒排表 / 向量库  | 表名+注释+字段名+真实取值     |
 *     | 召回 Retrieval  | 按相似度取 topK    | 按得分取 topK 张表           |
 *     | 增强 Augment    | 拼进 prompt       | 只把 topK 张表拼进 prompt    |
 *
 *   所以「Schema 召回」就是 RAG，只是把"文档"换成了"表结构"。
 *   简历上写"RAG 全链路"是站得住的 —— 但你要能说清这四环各自落在哪。
 *
 * ============================================================
 * 二、切块粒度为什么选「表」而不是「字段」
 * ============================================================
 *   写 SQL 时 JOIN 需要同时看到两侧表的字段。如果按字段切，
 *   召回 "amount" 可能只带回 t_transaction.amount，
 *   却丢掉 JOIN 必需的 t_account.account_id —— 模型拼不出正确 SQL。
 *
 *   结论：**切块粒度必须服从「下游任务的最小完整单位」**。
 *   这里的下游任务是"写一条 SQL"，它的最小完整单位就是"表"。
 *
 * ============================================================
 * 三、为什么 chunk 里要带「字段的真实取值」
 * ============================================================
 *   两个作用，第二个是本项目实测发现的关键点：
 *
 *   1. 渲染进 prompt：告诉模型 status 存的是中文「收入/支出」，
 *      否则它会写 WHERE status = 1 —— SQL 不报错但永远查不出数据。
 *
 *   2. ★ 作为召回信号：用户提问用的是**业务词**（"支出"、"餐饮"），
 *      而这些词恰恰就是字段的取值。把它们纳入检索文本后，
 *      "上个月支出多少" 才能命中 t_transaction —— 它的表注释里可没有"支出"二字。
 *      这是纯关键词召回里性价比最高的一招。
 *
 *   注意：本类只负责"装数据"，不含任何检索逻辑 —— 检索在 SchemaRetriever。
 */
public record SchemaChunk(String table, String comment, List<Column> columns) {

    /**
     * 一个字段。
     *
     * @param name       字段名
     * @param type       类型（如 varchar(10) / decimal(10,2)）
     * @param primaryKey 是否主键（渲染时会标 PK）
     * @param comment    字段注释（中文，是核心召回信号之一）
     * @param values     采样出的真实取值（低基数字段才有；已过滤敏感字段与展示型字段）
     */
    public record Column(String name, String type, boolean primaryKey,
                         String comment, List<String> values) {
    }
}
